import os
from dotenv import load_dotenv
from pydantic import BaseModel
from langchain_openai import ChatOpenAI
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import PydanticOutputParser
from langchain_classic.agents import create_tool_calling_agent, AgentExecutor
from tools import search_tool, wiki_tool, save_tool

#load_dotenv() is used to load environment variables from a .env file into the script's environment. This allows the script to access sensitive information, such as API keys, without hardcoding them into the codebase. In this case, it is used to load the NVIDIA_API_KEY from the .env file.
#only can be used in the main.py file, not in the tools.py file, because the tools.py file is imported into the main.py file, and the load_dotenv() function needs to be called before any environment variables are accessed. If it were called in the tools.py file, it would not be executed until the tools.py file is imported, which could lead to errors if the environment variables are accessed before they are loaded.
#load_dotenv() can be done after importing the os module and before accessing any environment variables. This ensures that the environment variables are available for use in the script.
load_dotenv()

#api_key is used to store the NVIDIA_API_KEY from the environment variables. This key is necessary for authenticating requests to the NVIDIA API, which is used by the ChatOpenAI model for generating research responses. By retrieving the API key from the environment variables, the script can securely access the NVIDIA API without exposing sensitive information in the codebase. 
api_key = os.getenv("NVIDIA_API_KEY")
# Stop early with a clear message if the key is missing, instead of a confusing authentication error later.
if not api_key:
    raise SystemExit("NVIDIA_API_KEY is not set. Add it to your .env file (see readme.md).")

#class ResearchResponse(BaseModel) defines a Pydantic model that specifies the structure of the research response generated by the language model. It includes four fields: topic (a string representing the research topic), summary (a string providing a brief overview of the research findings), sources (a list of strings containing references or sources used in the research), and tools_used (a list of strings indicating which tools were utilized during the research process). 
# This structured format ensures that the output from the language model is consistent and can be easily parsed and utilized in further processing or presentation. 
# this is basically a structure of the output topic, summary, sources, tools_used(citation) in a string format
class ResearchResponse(BaseModel):
    topic: str
    summary: str
    sources: list[str]
    tools_used: list[str]

#llm = ChatOpenAI creates an instance of the ChatOpenAI language model with specific parameters.
#It uses the "deepseek-ai/deepseek-v4.1-flash" model hosted at the NVIDIA API endpoint, authenticated with the provided API key.
#(The older "deepseek-ai/deepseek-v4-pro" was retired by NVIDIA on 2026-08-07 and now returns "410 Gone".)
#The temperature is set to 1 for more creative responses, and the maximum token limit is set to 16384 to allow for longer outputs.
#Additionally, the extra_body parameter is used to customize the chat template behavior, specifically disabling the "thinking" feature. 
#This instance of the language model will be used to generate research responses based on user queries and the structured prompt defined earlier.

# this is a function that defines what the standard or the conditions of the model is.
llm = ChatOpenAI(
    model="deepseek-ai/deepseek-v4.1-flash",
    base_url="https://integrate.api.nvidia.com/v1",
    api_key=api_key,
    temperature=1,
    max_tokens=16384,
    extra_body={"chat_template_kwargs": {"thinking": False}},
)

# Token is a unit that LLM reads and write; LLM doesnt process word by word nor text by text, they cut text into chunk of tokens and process them.
# the more token you use, the more you pay. So we need to be careful about the token usage. The max token is 16384, which is a lot.
# temperature controls how predictable vs random the models word choices are. 


# parser = PydanticOutputParser(pydantic_object=ResearchResponse) creates an instance of the PydanticOutputParser, 
# which is responsible for parsing the output generated by the language model into a structured format defined by the ResearchResponse Pydantic model. 
# This parser ensures that the output adheres to the expected structure, making it easier to work with and extract relevant information from the research response.
parser = PydanticOutputParser(pydantic_object=ResearchResponse)
prompt = ChatPromptTemplate.from_messages(
    [
        (
            "system",
            """
            You are a research assistant that will help generate a research paper.
            Answer the user query and use necessary tools.
            Wrap the output in this format and provide no other text\n{format_instructions}
            """,
        ),
        ("placeholder", "{chat_history}"),
        ("human", "{query}"),
        ("placeholder", "{agent_scratchpad}"),
    ]
).partial(format_instructions=parser.get_format_instructions())

tools = [search_tool, wiki_tool, save_tool]

# what ChatPromptTemplate.from_messages does is it creates a structured prompt for the language model,
#  which includes system instructions, user queries, and placeholders for chat history 
# and agent scratchpad. It allows the language model to understand the context of the conversation 
# and generate appropriate responses based on the user's query and the tools available 

#tools are the tools is imported as it was downloaded as part of the pip install -r requirements.txt file including wikipedia
#and ddgs and it was successfully imported search_tool, wiki_tool, save_tool from tools.py and now it can extract data from them.

agent = create_tool_calling_agent(llm=llm, prompt=prompt, tools=tools)
agent_executor = AgentExecutor(agent=agent, tools=tools, verbose=True)

# run_research() asks the user for a topic, lets the agent search Wikipedia / DuckDuckGo (the "retrieval" part of RAG),
# and then parses the model's answer into a ResearchResponse object.
def run_research():
    query = input("What can I help you research? ")
    raw_response = agent_executor.invoke({"query": query})

    try:
        structured_response = parser.parse(raw_response.get("output"))
        print(structured_response)
    except Exception as e:
        print("Error parsing response", e, "Raw Response - ", raw_response)


# if __name__ == "__main__": means "only run this when the file is started directly" (python main.py).
# Without it, other files that do `from main import llm` (like pseudocode.py) would also trigger the research prompt.
if __name__ == "__main__":
    run_research()

